create or replace function public.notification_push_server_secrets(p_dispatch_key text)
returns jsonb
language plpgsql
security definer
set search_path = public, vault
as $$
declare cfg public.notification_server_config%rowtype; v_private text;
begin
  select * into cfg from public.notification_server_config where singleton=true;
  if not found or encode(digest(coalesce(p_dispatch_key,''),'sha256'),'hex')<>cfg.dispatch_secret_hash then
    raise exception 'Invalid dispatcher key';
  end if;
  select decrypted_secret into v_private from vault.decrypted_secrets where name='gazalbide_vapid_private' order by created_at desc limit 1;
  if v_private is null then raise exception 'VAPID private key missing'; end if;
  return jsonb_build_object(
    'vapidPublicKey',cfg.vapid_public_key,
    'vapidPrivateKey',v_private,
    'vapidSubject',cfg.vapid_subject
  );
end;
$$;
revoke all on function public.notification_push_server_secrets(text) from public, anon, authenticated;
grant execute on function public.notification_push_server_secrets(text) to service_role;

create or replace function public.dispatch_push_notifications()
returns bigint
language plpgsql
security definer
set search_path = public, vault, extensions
as $$
declare cfg public.notification_server_config%rowtype; v_secret text; v_request_id bigint;
begin
  select * into cfg from public.notification_server_config where singleton=true;
  select decrypted_secret into v_secret from vault.decrypted_secrets where name='gazalbide_push_dispatch' order by created_at desc limit 1;
  if cfg.edge_function_url is null or v_secret is null then return null; end if;

  select net.http_post(
    url := cfg.edge_function_url,
    headers := jsonb_build_object('Content-Type','application/json','x-dispatch-key',v_secret),
    body := '{"limit":100}'::jsonb,
    timeout_milliseconds := 10000
  ) into v_request_id;
  return v_request_id;
end;
$$;
revoke all on function public.dispatch_push_notifications() from public, anon, authenticated;

-- Keep recent notification history without unbounded growth.
create or replace function public.cleanup_push_notifications()
returns void
language sql
security definer
set search_path = public
as $$
  delete from public.notification_outbox
  where created_at < now()-interval '90 days' and status in ('sent','skipped','failed');
$$;
revoke all on function public.cleanup_push_notifications() from public, anon, authenticated;
