-- Gazalbide Stats: Web Push notifications for the PWA.
-- Private VAPID/dispatcher secrets are provisioned separately in Supabase Vault.

create extension if not exists pg_cron with schema pg_catalog;
create extension if not exists pg_net with schema extensions;

create table if not exists public.notification_preferences (
  user_id uuid primary key references public.profiles(id) on delete cascade,
  enabled boolean not null default true,
  new_gameweek boolean not null default true,
  deadline_24h boolean not null default true,
  deadline_1h boolean not null default true,
  player_status boolean not null default true,
  match_live boolean not null default true,
  result_published boolean not null default true,
  prices_updated boolean not null default true,
  economy_ready boolean not null default true,
  updated_at timestamptz not null default now()
);

create table if not exists public.push_subscriptions (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references public.profiles(id) on delete cascade,
  endpoint text not null unique,
  p256dh text not null,
  auth_secret text not null,
  expiration_time bigint,
  user_agent text,
  active boolean not null default true,
  failure_count integer not null default 0 check (failure_count >= 0),
  last_success_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists push_subscriptions_user_active_idx
  on public.push_subscriptions(user_id, active);

create table if not exists public.notification_outbox (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  notification_type text not null check (notification_type in (
    'new_gameweek','deadline_24h','deadline_1h','player_status',
    'match_live','result_published','prices_updated','economy_ready'
  )),
  event_key text not null,
  title text not null,
  body text not null,
  route text not null default '/',
  tag text,
  payload jsonb not null default '{}'::jsonb,
  scheduled_for timestamptz not null default now(),
  status text not null default 'pending' check (status in ('pending','sending','sent','skipped','failed')),
  attempts integer not null default 0 check (attempts >= 0),
  claimed_at timestamptz,
  sent_at timestamptz,
  last_error text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (user_id, event_key)
);
create index if not exists notification_outbox_due_idx
  on public.notification_outbox(status, scheduled_for);
create index if not exists notification_outbox_user_created_idx
  on public.notification_outbox(user_id, created_at desc);

