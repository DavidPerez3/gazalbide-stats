create or replace function public.notification_delivery_eligible(o public.notification_outbox)
returns boolean
language plpgsql
stable
security definer
set search_path = public
as $$
declare v_gw bigint; v_match text;
begin
  if not coalesce(public.notification_type_enabled(o.user_id,o.notification_type),false) then return false; end if;

  if o.notification_type in ('deadline_24h','deadline_1h') then
    v_gw := nullif(o.payload->>'gameweekId','')::bigint;
    if not exists(select 1 from public.gameweeks gw where gw.id=v_gw and gw.status='scheduled' and gw.deadline>now()) then return false; end if;
    if o.notification_type='deadline_1h' and public.notification_lineup_valid(o.user_id,v_gw) then return false; end if;
  elsif o.notification_type='new_gameweek' then
    v_gw := nullif(o.payload->>'gameweekId','')::bigint;
    if not exists(select 1 from public.gameweeks gw where gw.id=v_gw and gw.status='scheduled' and gw.deadline>now()) then return false; end if;
  elsif o.notification_type='match_live' then
    v_match := o.payload->>'matchId';
    if not exists(select 1 from public.matches m where m.id=v_match and m.status='live') then return false; end if;
  end if;
  return true;
exception when others then
  return false;
end;
$$;
revoke all on function public.notification_delivery_eligible(public.notification_outbox)
  from public, anon, authenticated;

create or replace function public.claim_push_notification_batch(p_limit integer default 100)
returns setof public.notification_outbox
language plpgsql
security definer
set search_path = public
as $$
begin
  update public.notification_outbox
  set status='pending', claimed_at=null, updated_at=now()
  where status='sending' and claimed_at < now()-interval '10 minutes' and attempts<4;

  update public.notification_outbox o
  set status='skipped', last_error='preference_or_condition', updated_at=now()
  where o.status='pending' and o.scheduled_for<=now()
    and not public.notification_delivery_eligible(o);

  return query
  with picked as (
    select id from public.notification_outbox o
    where o.status='pending' and o.scheduled_for<=now()
      and public.notification_delivery_eligible(o)
    order by o.scheduled_for,o.id
    for update skip locked
    limit greatest(1,least(coalesce(p_limit,100),250))
  )
  update public.notification_outbox o
  set status='sending', attempts=o.attempts+1, claimed_at=now(), updated_at=now()
  from picked
  where o.id=picked.id
  returning o.*;
end;
$$;
revoke all on function public.claim_push_notification_batch(integer) from public, anon, authenticated;
