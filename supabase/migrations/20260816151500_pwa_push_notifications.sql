create or replace function public.register_push_subscription(
  p_endpoint text,
  p_p256dh text,
  p_auth_secret text,
  p_expiration_time bigint default null,
  p_user_agent text default null
)
returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare
  v_uid uuid := auth.uid();
  v_id uuid;
begin
  if v_uid is null then raise exception 'Authentication required'; end if;
  if coalesce(length(p_endpoint),0) < 10 or coalesce(length(p_p256dh),0) < 10 or coalesce(length(p_auth_secret),0) < 5 then
    raise exception 'Invalid push subscription';
  end if;

  insert into public.push_subscriptions(
    user_id, endpoint, p256dh, auth_secret, expiration_time, user_agent, active, failure_count, updated_at
  ) values (
    v_uid, p_endpoint, p_p256dh, p_auth_secret, p_expiration_time, left(p_user_agent,500), true, 0, now()
  )
  on conflict (endpoint) do update set
    user_id = excluded.user_id,
    p256dh = excluded.p256dh,
    auth_secret = excluded.auth_secret,
    expiration_time = excluded.expiration_time,
    user_agent = excluded.user_agent,
    active = true,
    failure_count = 0,
    updated_at = now()
  returning id into v_id;

  return v_id;
end;
$$;
revoke all on function public.register_push_subscription(text,text,text,bigint,text) from public, anon;
grant execute on function public.register_push_subscription(text,text,text,bigint,text) to authenticated;

