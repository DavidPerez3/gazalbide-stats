create or replace function public.notification_schedule_gameweek_for_user(p_user_id uuid, p_gameweek_id bigint)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  gw public.gameweeks%rowtype;
  v_name text;
begin
  select * into gw from public.gameweeks where id = p_gameweek_id;
  if not found or gw.status <> 'scheduled' or gw.deadline <= now() then return; end if;
  v_name := coalesce(gw.name, 'Nueva jornada');

  perform public.notification_enqueue_user(
    p_user_id,'deadline_24h','gw:'||gw.id||':deadline24',
    'Fantasy · quedan 24 horas',
    v_name || case when gw.opponent is not null then ' · vs '||gw.opponent else '' end || '. Revisa tu alineación.',
    '/fantasy','fantasy-deadline-'||gw.id,
    jsonb_build_object('gameweekId',gw.id),
    greatest(now(), gw.deadline - interval '24 hours')
  );
  perform public.notification_enqueue_user(
    p_user_id,'deadline_1h','gw:'||gw.id||':deadline1',
    'Fantasy · queda 1 hora',
    'Tu alineación todavía necesita atención antes del cierre.',
    '/fantasy','fantasy-deadline-'||gw.id,
    jsonb_build_object('gameweekId',gw.id,'requiresInvalidLineup',true),
    greatest(now(), gw.deadline - interval '1 hour')
  );
end;
$$;
revoke all on function public.notification_schedule_gameweek_for_user(uuid,bigint)
  from public, anon, authenticated;

