create policy "Users can view own lineups" on public.fantasy_lineups
  for select using (
    fantasy_team_id in (select ft.id from public.fantasy_teams ft where ft.user_id = auth.uid())
  );

drop policy if exists "Users can insert own lineups before deadline" on public.fantasy_lineups;
create policy "Users can insert own lineups before deadline" on public.fantasy_lineups
  for insert with check (
    fantasy_team_id in (select ft.id from public.fantasy_teams ft where ft.user_id = auth.uid())
    and exists (
      select 1 from public.gameweeks gw
      where gw.id = fantasy_lineups.gameweek_id
        and gw.status = 'scheduled'
        and now() < gw.deadline
    )
  );

drop policy if exists "Users can update own lineups before deadline" on public.fantasy_lineups;
create policy "Users can update own lineups before deadline" on public.fantasy_lineups
  for update using (
    fantasy_team_id in (select ft.id from public.fantasy_teams ft where ft.user_id = auth.uid())
    and exists (
      select 1 from public.gameweeks gw
      where gw.id = fantasy_lineups.gameweek_id
        and gw.status = 'scheduled'
        and now() < gw.deadline
    )
  );

drop policy if exists "Users can delete own lineups before deadline" on public.fantasy_lineups;
create policy "Users can delete own lineups before deadline" on public.fantasy_lineups
  for delete using (
    fantasy_team_id in (select ft.id from public.fantasy_teams ft where ft.user_id = auth.uid())
    and exists (
