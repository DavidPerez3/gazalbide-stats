comment on table public.fantasy_gameweek_economy is
  'Authoritative Fantasy budget state per team and gameweek. A skipped/invalid lineup finalizes with carry_out = 0.';
comment on column public.fantasy_gameweek_economy.carry_in is
  'Only carry from the immediately previous valid gameweek; users who skip rejoin with the new gameweek base budget.';
comment on column public.fantasy_gameweek_economy.carry_out is
  'Savings transferred to the next gameweek after applying the season max_carry limit.';
comment on column public.fantasy_teams.cervezas is
  'Compatibility cache for the currently opened Fantasy gameweek. The authoritative budget is fantasy_gameweek_economy.';
