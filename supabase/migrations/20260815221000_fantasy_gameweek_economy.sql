-- Gazalbide Stats: per-gameweek Fantasy economy with carry-over and audit ledger.
-- The authoritative budget moves from fantasy_teams.cervezas to one economy row per
-- Fantasy team and gameweek. fantasy_teams.cervezas remains as a compatibility cache.

alter table public.fantasy_season_settings
  add column if not exists max_carry integer not null default 20;

do $$
begin
  if not exists (
    select 1
    from pg_constraint
    where conname = 'fantasy_season_settings_max_carry_check'
      and conrelid = 'public.fantasy_season_settings'::regclass
  ) then
    alter table public.fantasy_season_settings
      add constraint fantasy_season_settings_max_carry_check
      check (max_carry >= 0);
  end if;
end
$$;

create table if not exists public.fantasy_gameweek_economy (
  fantasy_team_id uuid not null references public.fantasy_teams(id) on delete cascade,
  gameweek_id bigint not null references public.gameweeks(id) on delete cascade,
  base_budget integer not null check (base_budget > 0),
  carry_in integer not null default 0 check (carry_in >= 0),
  available_budget integer generated always as (base_budget + carry_in) stored,
  lineup_cost integer check (lineup_cost is null or lineup_cost >= 0),
  valid_lineup boolean not null default false,
  savings_generated integer not null default 0 check (savings_generated >= 0),
  carry_out integer not null default 0 check (carry_out >= 0),
  finalized_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  primary key (fantasy_team_id, gameweek_id)
);

create index if not exists fantasy_gameweek_economy_gameweek_idx
  on public.fantasy_gameweek_economy(gameweek_id);

create table if not exists public.fantasy_economy_ledger (
  id bigint generated by default as identity primary key,
  fantasy_team_id uuid not null references public.fantasy_teams(id) on delete cascade,
  gameweek_id bigint references public.gameweeks(id) on delete cascade,
  entry_type text not null check (
    entry_type in (
      'base_budget',
      'carry_in',
      'savings',
      'savings_cap',
      'le_gazal_bet',
      'le_gazal_payout',
      'prize',
      'loss',
      'admin_adjustment'
    )
  ),
  event_key text not null,
  amount integer not null,
  metadata jsonb not null default '{}'::jsonb,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  unique (fantasy_team_id, gameweek_id, event_key)
);

create index if not exists fantasy_economy_ledger_team_created_idx
  on public.fantasy_economy_ledger(fantasy_team_id, created_at desc);

create index if not exists fantasy_economy_ledger_gameweek_idx
  on public.fantasy_economy_ledger(gameweek_id);

alter table public.fantasy_gameweek_economy enable row level security;
alter table public.fantasy_economy_ledger enable row level security;

revoke all on public.fantasy_gameweek_economy from anon;
revoke all on public.fantasy_economy_ledger from anon;
grant select, insert, update, delete on public.fantasy_gameweek_economy to authenticated;
grant select, insert, update, delete on public.fantasy_economy_ledger to authenticated;
grant usage, select on sequence public.fantasy_economy_ledger_id_seq to authenticated;

